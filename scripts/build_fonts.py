#!/usr/bin/env python3
"""Rasterise Inter (SIL OFL) into 8-bit alpha glyph tables -> src/fonts/*.h.

Same format as tinyarcana's build_assets.py (src/aafont.h). The firmware
alpha-blends the glyphs itself; Arduino_GFX's 1-bit fonts are not used.

    python3 -m venv .venv && .venv/bin/pip install pillow
    .venv/bin/python scripts/build_fonts.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "assets", "fonts")
FONT_OUT = os.path.join(ROOT, "src", "fonts")

FIRST, LAST = 0x20, 0x7E
# Dutch destination names stay in ASCII in the feed today; the extras are a
# safety net for diacritics and the typographic glyphs the face draws.
EXTRA = sorted({ord(c) for c in "áàäâéèëêíïóöôúüçñÁÉÖÜ·–—…←→↑↓"})

FONTS = [
    # name, file, px, weight
    ("inter_label", "Inter.ttf", 14, 600),   # caps labels, tracked
    ("inter_dest", "Inter.ttf", 21, 500),    # destination on the hero row
    ("inter_badge", "Inter.ttf", 19, 700),   # line number in the badge
    ("inter_badge_s", "Inter.ttf", 13, 700), # line number in a small badge
    ("inter_big", "Inter.ttf", 50, 600),     # hero minutes
    ("inter_unit", "Inter.ttf", 16, 500),    # "min", follower text, status
]


def load_font(file, size, weight):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    try:
        axes = font.get_variation_axes()
        values = []
        for a in axes:
            name = a.get("name", b"")
            name = name.decode() if isinstance(name, bytes) else str(name)
            values.append(weight if "eight" in name or name == "wght"
                          else a.get("default", 0))
        font.set_variation_by_axes(values)
    except Exception as e:  # noqa: BLE001
        print("  (variation unavailable for %s: %s)" % (file, e))
    return font


def build_font(name, file, size, weight):
    font = load_font(file, size, weight)
    ascent, descent = font.getmetrics()
    glyphs = []
    alpha = bytearray()
    for code in list(range(FIRST, LAST + 1)) + EXTRA:
        ch = chr(code)
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        if w == 0 or h == 0:
            glyphs.append((len(alpha), 0, 0, 0, 0, adv))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        glyphs.append((len(alpha), w, h, x0, y0, adv))
        alpha += img.tobytes()

    path = os.path.join(FONT_OUT, name + ".h")
    with open(path, "w") as f:
        f.write("// Generated by scripts/build_fonts.py from %s @ %dpx wght %s."
                " Do not edit.\n" % (file, size, weight))
        f.write("#pragma once\n#include \"../aafont.h\"\n\n")
        f.write("static const uint8_t %s_alpha[] = {\n" % name)
        for i in range(0, len(alpha), 24):
            f.write("  " + ",".join(str(b) for b in alpha[i:i + 24]) + ",\n")
        f.write("};\n\nstatic const AaGlyph %s_glyphs[] = {\n" % name)
        for off, w, h, xo, yo, adv in glyphs:
            f.write("  {%d, %d, %d, %d, %d, %d},\n" % (off, w, h, xo, yo, adv))
        f.write("};\n\nstatic const uint16_t %s_codes[] = {\n" % name)
        for i in range(0, len(EXTRA), 12):
            f.write("  " + ",".join(str(c) for c in EXTRA[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("extern const AaFont %s;\nconst AaFont %s = "
                "{%s_alpha, %s_glyphs, %s_codes, %d, %d, %d, %d, %d};\n"
                % (name, name, name, name, name, len(EXTRA), FIRST, LAST,
                   ascent + descent, ascent))
    print("font: %-14s %dpx -> %s (%d KB)"
          % (name, size, os.path.relpath(path, ROOT), len(alpha) // 1024))


if __name__ == "__main__":
    os.makedirs(FONT_OUT, exist_ok=True)
    for spec in FONTS:
        build_font(*spec)
